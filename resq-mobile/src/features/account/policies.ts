export const policyById = (id: string): Policy | undefined => POLICIES.find(p => p.id === id);

export type PolicyBlock =
  | { kind: 'heading'; text: string }
  | { kind: 'paragraph'; text: string }
  | { kind: 'table'; header: string[]; rows: string[][] };

/** Dựng khối hiển thị từ các dòng văn bản (gom các hàng bảng liền nhau). */
export function policyBlocks(lines: readonly string[]): PolicyBlock[] {
  const out: PolicyBlock[] = [];
  for (const raw of lines) {
    const line = raw.trim();
    if (!line) continue;
    if (line.includes(' | ')) {
      const cells = line.split(' | ').map(c => c.trim());
      const last = out[out.length - 1];
      if (last && last.kind === 'table') last.rows.push(cells);
      else out.push({ kind: 'table', header: cells, rows: [] });
      continue;
    }
    const isHeading = line.length <= 90 && !/[.:;!?…]$/.test(line);
    out.push(isHeading ? { kind: 'heading', text: line } : { kind: 'paragraph', text: line });
  }
  return out;
}
